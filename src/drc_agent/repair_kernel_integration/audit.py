def integration_code_digest(root: Path | None = None) -> str:
    """Return the deterministic digest of executable integration modules.

    The digest intentionally covers only the adapter package's tracked Python
    sources (not generated bytecode or run artifacts), so manifests can bind a
    runtime to the exact integration implementation without a Git commit.
    """
    package_root = root or Path(__file__).resolve().parent
    files = sorted(package_root.glob("*.py"))
    return stable_hash({item.name: file_sha256(item) for item in files})


