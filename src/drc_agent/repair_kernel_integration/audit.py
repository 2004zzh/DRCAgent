def p4_v2_source_digest(project_root: Path | None = None) -> str:
    """Bind scoped P4-v2 evaluation to every executable project module.

    Generated contracts, profiles, reports, run artifacts, caches and tests
    are deliberately excluded.  Their identities are bound separately, which
    avoids self-referential manifest hashes.
    """
    root = project_root or Path(__file__).resolve().parents[3]
    package = root / "src" / "drc_agent"
    manifest = {
        str(path.relative_to(root)): file_sha256(path)
        for path in sorted(package.rglob("*"))
        if path.is_file()
        and (path.suffix == ".py" or ".so" in path.suffixes)
    }
    return stable_hash(manifest)


